import { test, expect } from '@playwright/test';
import { pdfFixture } from './pdfFixture';

test('论文详情拖动宽度、取消、键盘、收放及重启记忆，并保留手机全宽', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/'); await page.getByRole('button', { name: '文献库', exact: true }).click();
  const ui = page.frameLocator('.port-library-shell iframe');
  await expect(ui.locator('#port-status')).toContainText('已就绪');
  await ui.locator('#port-pdf-input').setInputFiles([{ name: 'Resizable Detail.pdf', mimeType: 'application/pdf', buffer: pdfFixture('Resizable detail pane') }]);
  await ui.locator('.rw-paper-title').click();
  const pane = ui.getByRole('complementary', { name: '论文详情', exact: true });
  const handle = ui.getByRole('separator', { name: '调整论文详情宽度', exact: true });
  const width = () => pane.evaluate(el => Math.round(el.getBoundingClientRect().width));
  const start = await width();
  const listStart = await ui.locator('.rw-paper-list').evaluate(el => Math.round(el.getBoundingClientRect().width));
  const drag = async (delta, cancel = false) => {
    const box = await handle.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 - delta, box.y + box.height / 2, { steps: 8 });
    if (cancel) await handle.press('Escape');
    await page.mouse.up();
  };
  await drag(140);
  await expect.poll(width).toBe(start + 140);
  expect(await ui.locator('.rw-paper-list').evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(listStart - 140);
  await drag(50, true); await expect.poll(width).toBe(start + 140);
  expect(await ui.locator('body').evaluate(el => el.classList.contains('rw-resizing-detail'))).toBe(false);
  await handle.focus(); await handle.press('Shift+ArrowLeft'); await expect.poll(width).toBe(start + 180);
  await page.screenshot({ path: 'shots/detail-resize-desktop.png' });
  await page.reload(); await page.getByRole('button', { name: '文献库', exact: true }).click();
  await expect.poll(width).toBe(start + 180);
  await ui.getByRole('button', { name: '关闭论文详情', exact: true }).click();
  await expect(ui.locator('.rw-detail-resizer')).toHaveCount(0);
  await ui.getByRole('button', { name: '展开论文详情', exact: true }).click();
  await expect.poll(width).toBe(start + 180);
  await handle.focus(); await handle.press('End'); await expect.poll(width).toBe(560);
  expect(await ui.locator('.rw-paper-list').evaluate(el => el.getBoundingClientRect().width)).toBeGreaterThanOrEqual(320);
  await handle.press('ArrowRight'); await expect.poll(width).toBe(550);
  await handle.dblclick(); await expect.poll(width).toBe(start);
  await drag(100);
  await page.setViewportSize({ width: 390, height: 844 });
  await ui.locator('.rw-paper-title').click();
  await expect(pane).toBeVisible(); await expect(ui.locator('.rw-detail-resizer')).toBeHidden();
  expect(await pane.evaluate(el => el.getBoundingClientRect().width)).toBeGreaterThan(360);
  expect(await ui.locator('html').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: 'shots/detail-resize-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect.poll(width).toBe(start + 100);
  await handle.focus(); await handle.press('Home'); await expect.poll(width).toBe(start);
  expect(errors).toEqual([]);
});
