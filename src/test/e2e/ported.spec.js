test('MuPDF 原渲染内核、批注编辑、区域预览与重启持久化', async ({ page }) => {
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');await page.getByRole('button',{name:'文献库',exact:true}).click();
  const ui=page.frameLocator('.port-library-shell iframe');await expect(ui.locator('#port-status')).toContainText('文献库已就绪');
  await ui.locator('#port-pdf-input').setInputFiles([{name:'MuPDF Test.pdf',mimeType:'application/pdf',buffer:pdfFixture('Text selection and annotation persistence')}]);
  await expect(ui.locator('.rw-paper-row')).toHaveCount(1);
  let frame=page.frames().find(frame=>frame.url().includes('port.html'));
  await ui.getByRole('button',{name:'阅读 MuPDF Test',exact:true}).click();
  await expect(ui.locator('.mupdf-reader-status')).toContainText('1 页 · MuPDF');
  await expect.poll(()=>ui.locator('.mupdf-reader-canvas').first().evaluate(canvas=>canvas.width)).toBeGreaterThan(8);
  await frame.evaluate(async()=>{const x=window.__researchPort;const path=x.app.workspace.getActiveFile().path;await x.reader.addAnnotation(path,{id:'portable-note-test',type:'note',page:0,text:'',comment:'Initial comment',tags:['方法'],quads:[],x:80,y:110,color:'yellow',createdAt:Date.now(),updatedAt:Date.now(),presentation:{pinned:true}});await x.reader.openAnnotationEditor(path,'portable-note-test');});
  await ui.getByRole('textbox',{name:'便签内容'}).fill('Migrated comment survives restart');
  await ui.getByRole('button',{name:'保存',exact:true}).click();
  await ui.getByRole('button',{name:'打开研究侧栏',exact:true}).click();
  await expect(ui.locator('#reader-sidebar')).toBeVisible();
  await expect(ui.locator('#reader-sidebar')).toContainText('Migrated comment survives restart');
  const region = await frame.evaluate(async()=>{const x=window.__researchPort;const path=x.app.workspace.getActiveFile().path;const engine=x.app.workspace.mainLeaf.view.reader;const rect=[40,20,340,90];const preview=await engine.renderRegionPreview(0,rect);if(!preview?.dataUrl)throw new Error('Region rendering failed');await x.reader.addAnnotation(path,{id:'portable-region-test',type:'region',page:0,rect,quads:[],text:'',comment:'Region clip',tags:['方法图'],color:'blue',previewDataUrl:preview.dataUrl,previewWidth:preview.width,previewHeight:preview.height,previewVersion:preview.previewVersion});return{width:preview.width,previewVersion:preview.previewVersion};});
  expect(region.width).toBeGreaterThan(300);expect(region.previewVersion).toBe(2);
  await page.screenshot({path:'shots/ported-reader-test.png'});
  await ui.locator('#reader-back').click();
  await ui.getByRole('tab',{name:/^摘录/}).click();
  await expect(ui.locator('.rw-annotation')).toHaveCount(2);
  await expect(ui.locator('.rw-annotation')).toContainText(['Migrated comment survives restart','Region clip']);
  await ui.getByRole('tab',{name:'图表摘录',exact:true}).click();
  await expect(ui.locator('.rw-figure img')).toHaveCount(1);
  await ui.getByRole('tab',{name:'阅读记录',exact:true}).click();
  await expect(ui.locator('.rw-excerpt-row')).toHaveCount(2);
  await page.reload();await page.getByRole('button',{name:'文献库',exact:true}).click();
  await expect(ui.locator('#port-status')).toContainText('文献库已就绪');
  frame=page.frames().find(frame=>frame.url().includes('port.html'));
  expect(await frame.evaluate(()=>window.__researchPort.reader.getAllAnnotations().find(row=>row.annotation.id==='portable-note-test')?.annotation.comment)).toBe('Migrated comment survives restart');
  expect(await frame.evaluate(()=>{const x=window.__researchPort;const annotation=x.reader.getAllAnnotations().find(row=>row.annotation.id==='portable-region-test')?.annotation;return!!annotation?.previewPath&&!!x.vault.getResourcePath({path:annotation.previewPath});})).toBe(true);
  // Imported reader records can exist without a matching literature note.
  await frame.evaluate(async()=>{const x=window.__researchPort;await x.vault.delete(x.library.currentModal.papers[0].file);});
  await expect(ui.locator('.rw-paper-row')).toHaveCount(0);
  await ui.getByRole('tab',{name:'阅读记录',exact:true}).click();
  await expect(ui.locator('.rw-excerpt-row')).toHaveCount(2);
  await ui.getByRole('tab',{name:'图表摘录',exact:true}).click();
  await expect(ui.locator('.rw-figure img')).toHaveCount(1);
  expect(errors).toEqual([]);
});

test('窄屏分类抽屉、论文详情返回和筛选导出保持可用', async ({ page }) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');await page.getByRole('button',{name:'文献库',exact:true}).click();
  const ui=page.frameLocator('.port-library-shell iframe');
  await expect(ui.getByRole('heading',{name:'全部文献',exact:true})).toBeVisible();
  await ui.locator('#port-pdf-input').setInputFiles([{name:'Narrow Study.pdf',mimeType:'application/pdf',buffer:pdfFixture('A paper for responsive interactions')}]);
  await expect(ui.locator('.rw-paper-row')).toHaveCount(1);
  await ui.locator('.rw-paper-row').click();
  await expect(ui.getByRole('complementary',{name:'论文详情'})).toBeVisible();
  await chooseReadingState(ui, '论文阅读状态', 'queued');
  await ui.getByRole('button',{name:'返回文献列表',exact:true}).click();
  await expect(ui.locator('.rw-paper-row .rw-state')).toHaveText('待阅读');
  await ui.getByRole('button',{name:'打开文献分类',exact:true}).click();
  await ui.getByRole('navigation',{name:'快捷文献视图'}).getByRole('button',{name:/^待阅读/}).click();
  await expect(ui.getByRole('heading',{level:2,name:'待阅读',exact:true})).toBeVisible();
  await expect(ui.locator('.rw-paper-row')).toHaveCount(1);
  await ui.getByRole('button',{name:'筛选',exact:true}).click();
  await ui.getByLabel('筛选阅读状态').selectOption('read');
  await expect(ui.locator('.rw-paper-row')).toHaveCount(0);
  await ui.getByRole('button',{name:'重置筛选',exact:true}).click();
  await expect(ui.locator('.rw-paper-row')).toHaveCount(1);
  await ui.getByRole('button',{name:'更多文献工具',exact:true}).click();
  const download=page.waitForEvent('download');
  await ui.getByRole('menuitem',{name:'导出 BibTeX',exact:true}).click();
  expect((await download).suggestedFilename()).toBe('references.bib');
  const frame=page.frames().find(frame=>frame.url().includes('port.html'));
  expect(await frame.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
  await page.screenshot({path:'shots/ported-library-mobile-test.png'});
});
