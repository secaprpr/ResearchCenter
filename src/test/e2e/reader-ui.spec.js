import { test, expect } from '@playwright/test';
import { pdfFixture } from './pdfFixture';

test('统一阅读器保留真实选区高亮、批注、框选摘录与窄屏面板', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '文献库', exact: true }).click();
  const ui = page.frameLocator('.port-library-shell iframe');
  await expect(ui.locator('#port-status')).toContainText('文献库已就绪');
  await ui.locator('#port-pdf-input').setInputFiles([{ name: 'Reader workflow.pdf', mimeType: 'application/pdf', buffer: pdfFixture('Reading notes keep evidence connected') }]);
  await ui.locator('.rw-paper-row').first().click();
  await ui.getByRole('button', { name: '阅读 PDF', exact: true }).click();
  await expect(ui.locator('.mupdf-reader-toolbar')).toHaveAttribute('data-workbench', 'true');
  await expect.poll(() => ui.locator('.mupdf-reader-canvas').first().evaluate(canvas => canvas.width)).toBeGreaterThan(8);
  const highlight = ui.getByRole('button', { name: '高亮选区', exact: true });
  await expect(highlight).toBeVisible(); await expect(highlight).toBeDisabled();
  await ui.getByRole('button', { name: '在 PDF 空间添加便签', exact: true }).click();
  await expect(ui.locator('.mupdf-reader-note-placement-btn')).toHaveAttribute('aria-pressed', 'true');
  await ui.locator('.mupdf-reader-root').press('Escape');
  await expect(ui.locator('.mupdf-reader-note-placement-btn')).toHaveAttribute('aria-pressed', 'false');
  const dragPdf = async (start, end) => {
    const box = await ui.locator('.mupdf-reader-page').first().boundingBox();
    const scale = box.width / 612;
    await page.mouse.move(box.x + start[0] * scale, box.y + start[1] * scale);
    await page.mouse.down();
    await page.mouse.move(box.x + end[0] * scale, box.y + end[1] * scale, { steps: 12 });
    await page.mouse.up();
  };
  await dragPdf([51, 26], [350, 35]);
  await expect(highlight).toBeEnabled(); await highlight.click();
  await expect(ui.locator('.mupdf-reader-highlight-quad').first()).toBeVisible();
  await dragPdf([51, 26], [350, 35]);
  await ui.getByRole('button', { name: '添加批注（保存为高亮）', exact: true }).click();
  await ui.getByRole('textbox', { name: '批注内容', exact: true }).fill('复现时核对这个假设');
  await ui.getByRole('button', { name: '保存', exact: true }).click();
  await ui.getByRole('button', { name: '框选图、表或任意 PDF 区域', exact: true }).click();
  await expect(ui.locator('.mupdf-reader-region-capture-btn')).toHaveAttribute('aria-pressed', 'true');
  await dragPdf([50, 65], [300, 140]);
  await expect(ui.locator('.mupdf-comment-region-preview img')).toBeVisible();
  await ui.getByRole('textbox', { name: '区域摘录说明', exact: true }).fill('组会使用的图表摘录');
  await ui.getByRole('button', { name: '保存', exact: true }).click();
  await ui.getByRole('button', { name: '打开研究侧栏', exact: true }).click();
  await expect(ui.locator('#reader-sidebar')).toContainText('复现时核对这个假设');
  await expect(ui.locator('#reader-sidebar')).toContainText('组会使用的图表摘录');
  const sidebarToggle = ui.locator('.mupdf-reader-sidebar-btn');
  await expect(sidebarToggle).toHaveAttribute('aria-expanded', 'true');
  await sidebarToggle.click(); await expect(ui.locator('#reader-sidebar')).toBeHidden();
  await expect(sidebarToggle).toHaveAttribute('aria-expanded', 'false');
  await sidebarToggle.click(); await expect(ui.locator('#reader-sidebar')).toContainText('组会使用的图表摘录');
  const pin = ui.locator('.mupdf-research-pin-toggle');
  await pin.click(); await expect(pin).toHaveAttribute('aria-pressed', 'true');
  await pin.click(); await expect(pin).toHaveAttribute('aria-pressed', 'false');
  await expect(ui.locator('#notices .notice')).toHaveCount(0);
  await page.screenshot({ path: 'shots/reader-workflow-desktop.png' });
  await ui.getByRole('button', { name: '收起 PDF 批注', exact: true }).click();
  await expect(ui.locator('#reader-sidebar')).toBeHidden();
  await expect(sidebarToggle).toHaveAttribute('aria-expanded', 'false');
  await page.setViewportSize({ width: 390, height: 844 });
  await ui.getByRole('button', { name: '打开研究侧栏', exact: true }).click();
  await expect(ui.getByRole('button', { name: '收起 PDF 批注', exact: true })).toBeInViewport();
  await page.screenshot({ path: 'shots/reader-workflow-mobile.png' });
  await ui.getByRole('button', { name: '收起 PDF 批注', exact: true }).click();
  expect(await ui.locator('body').evaluate(el => el.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.reload(); await page.getByRole('button', { name: '文献库', exact: true }).click();
  await ui.locator('.rw-paper-row').first().click();
  await ui.getByRole('button', { name: '阅读 PDF', exact: true }).click();
  await ui.getByRole('button', { name: '打开研究侧栏', exact: true }).click();
  await expect(ui.locator('#reader-sidebar')).toContainText('复现时核对这个假设');
  await expect(ui.locator('#reader-sidebar')).toContainText('组会使用的图表摘录');
  expect(errors).toEqual([]);
});
